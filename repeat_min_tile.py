import networkx as nx

def MinimumRepeatTile(G: nx.Graph, w: int, h: int) -> set:
    S = set()
    for i in range(1, w // 5 - 1):
        for j in range(1, h // 5 - 1):
            S.update({(0+5*i, 0+5*j), (0+5*i, 1+5*j), (1+5*i, 2+5*j), (1+5*i, 3+5*j), (2+5*i, 4+5*j), (2+5*i, 0+5*j), (3+5*i, 1+5*j), (3+5*i, 2+5*j), (4+5*i, 3+5*j), (4+5*i, 4+5*j)})
    
    for i in range(1, w // 5 - 1):
        S.update({(0+5*i, 0), (0+5*i, 1), (1+5*i, 2), (1+5*i, 3), (1+5*i, 4), (2+5*i, 4), (2+5*i, 0), (3+5*i, 1), (3+5*i, 2), (4+5*i, 3), (4+5*i, 4)})
        j = h // 5 - 1
        S.update({(0+5*i, 0+5*j), (0+5*i, 1+5*j), (1+5*i, 2+5*j), (1+5*i, 3+5*j), (2+5*i, 4+5*j), (2+5*i, 0+5*j), (3+5*i, 0+5*j), (3+5*i, 1+5*j), (3+5*i, 2+5*j), (4+5*i, 3+5*j), (4+5*i, 4+5*j)})

    for j in range(1, h // 5 - 1):
        S.update({(0, 0+5*j), (0, 1+5*j), (0, 3+5*j), (1, 2+5*j), (1, 3+5*j), (2, 4+5*j), (2, 0+5*j), (3, 1+5*j), (3, 2+5*j), (4, 3+5*j), (4, 4+5*j)})
        i = w // 5 - 1
        S.update({(0+5*i, 0+5*j), (0+5*i, 1+5*j), (1+5*i, 2+5*j), (1+5*i, 3+5*j), (2+5*i, 4+5*j), (2+5*i, 0+5*j), (3+5*i, 1+5*j), (3+5*i, 2+5*j), (4+5*i, 1+5*j), (4+5*i, 3+5*j), (4+5*i, 4+5*j)})
    
    i = w // 5 - 1
    j = h // 5 - 1
    S.update({(0, 0), (0, 1), (0, 3), (1, 2), (1, 3), (2, 4), (2, 0), (3, 0), (3, 1), (3, 2), (4, 3), (4, 4)})
    S.update({(0+5*i, 0), (0+5*i, 1), (1+5*i, 2), (1+5*i, 3), (2+5*i, 4), (2+5*i, 0), (3+5*i, 0), (3+5*i, 1), (3+5*i, 2), (4+5*i, 1), (4+5*i, 3), (4+5*i, 4)})
    S.update({(0, 0+5*j), (0, 1+5*j), (0, 3+5*j), (1, 2+5*j), (1, 3+5*j), (1, 4+5*j), (2, 4+5*j), (2, 0+5*j), (3, 1+5*j), (3, 2+5*j), (4, 3+5*j), (4, 4+5*j)})
    S.update({(0+5*i, 0+5*j), (0+5*i, 1+5*j), (1+5*i, 2+5*j), (1+5*i, 3+5*j), (1+5*i, 4+5*j), (2+5*i, 4+5*j), (2+5*i, 0+5*j), (3+5*i, 1+5*j), (3+5*i, 2+5*j), (4+5*i, 1+5*j), (4+5*i, 3+5*j), (4+5*i, 4+5*j)})
    
    return S

m = 15
n = 10
G = nx.grid_2d_graph(m, n)
gammax2set = MinimumRepeatTile(G, m, n)

print(f"Minimum double dominating set: {gammax2set}")